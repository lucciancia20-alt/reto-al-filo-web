/**
 * Interpola la posición exacta { km, alt, lat, lon } sobre el recorrido real
 * para cualquier kilómetro ingresado (ej. puesto de hidratación).
 */
export function interpolatePointAtKm(trackPoints, targetKm) {
  if (!Array.isArray(trackPoints) || trackPoints.length === 0) {
    return { km: Number(targetKm) || 0, alt: 0, lat: 0, lon: 0 };
  }

  const kmVal = Number(targetKm);
  if (Number.isNaN(kmVal) || kmVal <= trackPoints[0].km) {
    return { ...trackPoints[0] };
  }

  const last = trackPoints[trackPoints.length - 1];
  if (kmVal >= last.km) {
    return { ...last };
  }

  for (let i = 0; i < trackPoints.length - 1; i++) {
    const a = trackPoints[i];
    const b = trackPoints[i + 1];
    if (kmVal >= a.km && kmVal <= b.km) {
      const span = b.km - a.km;
      const t = span > 0 ? (kmVal - a.km) / span : 0;
      return {
        km: Number(kmVal.toFixed(2)),
        alt: Math.round(a.alt + (b.alt - a.alt) * t),
        lat: Number((a.lat + (b.lat - a.lat) * t).toFixed(6)),
        lon: Number((a.lon + (b.lon - a.lon) * t).toFixed(6)),
      };
    }
  }

  return { ...last };
}

/**
 * Parsea un archivo .gpx en el navegador (para carga dinámica desde el Panel Admin).
 */
export function parseGpxXml(xmlText, targetTotalKm = null) {
  const parser = new DOMParser();
  const doc = parser.parseFromString(xmlText, 'application/xml');
  const trkpts = Array.from(doc.getElementsByTagName('trkpt'));
  if (trkpts.length < 2) {
    throw new Error('El archivo GPX no contiene suficientes puntos de track (<trkpt>).');
  }

  const toRad = (deg) => (deg * Math.PI) / 180;
  const haversine = (lat1, lon1, lat2, lon2) => {
    const R = 6371;
    const dLat = toRad(lat2 - lat1);
    const dLon = toRad(lon2 - lon1);
    const a =
      Math.sin(dLat / 2) ** 2 +
      Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLon / 2) ** 2;
    return 2 * R * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  };

  const rawPoints = [];
  let cumKm = 0;
  let prevLat = null;
  let prevLon = null;

  for (const pt of trkpts) {
    const lat = parseFloat(pt.getAttribute('lat'));
    const lon = parseFloat(pt.getAttribute('lon'));
    if (Number.isNaN(lat) || Number.isNaN(lon)) continue;

    if (prevLat !== null) {
      cumKm += haversine(prevLat, prevLon, lat, lon);
    }
    prevLat = lat;
    prevLon = lon;

    const eleEl = pt.getElementsByTagName('ele')[0];
    const alt = eleEl ? parseFloat(eleEl.textContent) : 0;

    let distKm = cumKm;
    const distEl =
      pt.getElementsByTagName('gpxdata:distance')[0] ||
      pt.getElementsByTagNameNS('*', 'distance')[0];
    if (distEl && !Number.isNaN(parseFloat(distEl.textContent))) {
      distKm = parseFloat(distEl.textContent) / 1000;
    }

    rawPoints.push({ lat, lon, alt: Number.isNaN(alt) ? 0 : alt, rawKm: distKm });
  }

  const rawTotalKm = rawPoints[rawPoints.length - 1].rawKm || cumKm;
  const effectiveTargetKm = targetTotalKm ? Number(targetTotalKm) : Number(rawTotalKm.toFixed(2));
  const scale = rawTotalKm > 0 ? effectiveTargetKm / rawTotalKm : 1;

  let minAlt = Infinity;
  let maxAlt = -Infinity;
  let peakIndex = 0;
  let gain = 0;

  for (let i = 0; i < rawPoints.length; i++) {
    const p = rawPoints[i];
    if (p.alt < minAlt) minAlt = p.alt;
    if (p.alt > maxAlt) {
      maxAlt = p.alt;
      peakIndex = i;
    }
    if (i > 0 && p.alt > rawPoints[i - 1].alt) {
      gain += p.alt - rawPoints[i - 1].alt;
    }
  }

  const targetCount = Math.min(160, rawPoints.length);
  const indices = new Set([0, peakIndex, rawPoints.length - 1]);
  for (let i = 1; i < targetCount - 1; i++) {
    indices.add(Math.round((i / (targetCount - 1)) * (rawPoints.length - 1)));
  }

  const points = [...indices]
    .sort((a, b) => a - b)
    .map((idx) => {
      const p = rawPoints[idx];
      return {
        km: Number((p.rawKm * scale).toFixed(3)),
        rawKm: Number(p.rawKm.toFixed(3)),
        alt: Math.round(p.alt),
        lat: Number(p.lat.toFixed(6)),
        lon: Number(p.lon.toFixed(6)),
      };
    });

  const peakPt = rawPoints[peakIndex];
  return {
    totalKm: effectiveTargetKm,
    rawTotalKm: Number(rawTotalKm.toFixed(2)),
    minAlt: Math.round(minAlt),
    maxAlt: Math.round(maxAlt),
    elevationGain: Math.round(gain),
    peakKm: Number((peakPt.rawKm * scale).toFixed(2)),
    peakRawKm: Number(peakPt.rawKm.toFixed(2)),
    peakAlt: Math.round(peakPt.alt),
    startCoord: [Number(rawPoints[0].lat.toFixed(6)), Number(rawPoints[0].lon.toFixed(6))],
    points,
  };
}
